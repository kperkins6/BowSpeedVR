"""Generate immutable runtime tables without changing the complete saved inventory.

Profile numbers come only from matched-pair-design.json; reviewed CSV policy and
profile columns determine bindings. Never infer eligibility from material/name.
"""
import argparse
import csv
from decimal import Decimal, localcontext
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GRAVITY_EXCEPTIONS = {
    ("dis_heavy_legion.esp", 0x898),
    ("legacyofthedragonborn.esm", 0x236D52),
    ("elvenia armor.esp", 0x816),
}


def quote(text):
    return json.dumps(text, ensure_ascii=True)


def number(value):
    if not value.is_finite() or value <= 0:
        raise ValueError(f"Invalid profile number: {value}")
    return str(value)


def inventory(filename):
    with (ROOT / "data" / filename).open(encoding="utf-8-sig", newline="") as source:
        return list(csv.DictReader(source))


def form(row):
    plugin, identifier = row["Form"].split("|")
    local = int(identifier, 16)
    if not plugin or not 0 < local <= 0xFFFFFF:
        raise ValueError(f"Invalid inventory form: {row['Form']}")
    return plugin.lower(), local


def bindings(rows, profiles, bow):
    selected = []
    seen = set()
    for row in rows:
        plugin, local = form(row)
        policy = row["Policy"]
        include = (policy == "Player bow candidate" or policy.startswith("Summoned candidate:")) if bow else policy == "Player arrow candidate"
        if not include or (bow and plugin == "vigilant.esm"):
            continue
        if row["Profile"] not in profiles:
            raise ValueError(f"Unknown profile for {row['Form']}: {row['Profile']}")
        key = plugin, local
        if key in seen:
            raise ValueError(f"Duplicate binding: {row['Form']}")
        seen.add(key)
        selected.append((plugin, local, row["Profile"]))
    return sorted(selected)


def generate():
    design = json.loads((ROOT / "data" / "matched-pair-design.json").read_text(encoding="utf-8"), parse_float=Decimal, parse_int=Decimal)
    bows = design["bowProfiles"]
    arrows = design["arrowProfiles"]
    bow_bindings = bindings(inventory("bow-records.csv"), bows, True)
    arrow_bindings = bindings(inventory("ammo-records.csv"), arrows, False)
    excluded = {}
    for row in inventory("bow-records.csv") + inventory("ammo-records.csv"):
        if row["Policy"].startswith("Exclude:"):
            excluded[form(row)] = row["Policy"]
    if (len(bows), len(arrows), len(bow_bindings), len(arrow_bindings)) != (34, 21, 588, 25):
        raise ValueError("Reviewed catalogue counts changed; review inventory policy before regenerating")
    if not GRAVITY_EXCEPTIONS <= {(p, i) for p, i, _ in arrow_bindings}:
        raise ValueError("A reviewed gravity exception is missing")
    lines = [
        "// Generated by scripts/generate-physics-catalog.py. Do not edit by hand.",
        "// All source inventory rows remain in data/; only reviewed candidates bind here.",
        '#include "BowSpeed/PhysicsCatalog.h"',
        "namespace BowSpeed {", "namespace {", "constexpr BowPhysicsProfile kBows[] = {",
    ]
    with localcontext() as context:
        context.prec = 50
        for name in sorted(bows, key=str.casefold):
            lines.append(f"    {{{quote(name)}, {number(bows[name]['Q'] / Decimal('1.25'))}}},")
    lines += ["};", "constexpr ArrowPhysicsProfile kArrows[] = {"]
    for name in sorted(arrows, key=str.casefold):
        p = arrows[name]
        lines.append(f"    {{{quote(name)}, {number(p['mass'])}, {number(p['capacityQ'])}, {number(p['dragArea'])}}},")
    lines += ["};", "constexpr BowPhysicsBinding kBowBindings[] = {"]
    for plugin, local, profile in bow_bindings:
        lines.append(f"    {{{quote(plugin)}, 0x{local:06X}, {quote(profile)}}},")
    lines += ["};", "constexpr ArrowPhysicsBinding kArrowBindings[] = {"]
    for plugin, local, profile in arrow_bindings:
        gravity = "true" if (plugin, local) in GRAVITY_EXCEPTIONS else "false"
        lines.append(f"    {{{quote(plugin)}, 0x{local:06X}, {quote(profile)}, {gravity}}},")
    lines += ["};", "constexpr EquipmentExclusion kExclusions[] = {"]
    for (plugin, local), reason in sorted(excluded.items()):
        lines.append(f"    {{{quote(plugin)}, 0x{local:06X}, {quote(reason)}}},")
    lines += ["};", """// ASCII folding is independent of the process locale and needs no allocation.
constexpr char Fold(char c) noexcept { return c>='A' && c<='Z' ? static_cast<char>(c+('a'-'A')) : c; }
bool EqualName(std::string_view a, std::string_view b) noexcept {
    if (a.size()!=b.size()) return false;
    for (std::size_t i=0; i<a.size(); ++i) if (Fold(a[i])!=Fold(b[i])) return false;
    return true;
}
}
std::span<const BowPhysicsProfile> BowPhysicsProfiles() noexcept { return kBows; }
std::span<const ArrowPhysicsProfile> ArrowPhysicsProfiles() noexcept { return kArrows; }
std::span<const BowPhysicsBinding> DefaultBowPhysicsBindings() noexcept { return kBowBindings; }
std::span<const ArrowPhysicsBinding> DefaultArrowPhysicsBindings() noexcept { return kArrowBindings; }
std::span<const EquipmentExclusion> ReviewedEquipmentExclusions() noexcept { return kExclusions; }
const BowPhysicsProfile* FindBowPhysicsProfile(std::string_view name) noexcept {
    for (const auto& profile:kBows) if (EqualName(name,profile.name)) return &profile;
    return nullptr;
}
const ArrowPhysicsProfile* FindArrowPhysicsProfile(std::string_view name) noexcept {
    for (const auto& profile:kArrows) if (EqualName(name,profile.name)) return &profile;
    return nullptr;
}
}
"""]
    return "\n".join(lines).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in output differs; write nothing")
    parser.add_argument("--output", type=Path, default=ROOT / "src" / "PhysicsCatalog.cpp")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        # Git may check out CRLF on Windows. Generation always writes canonical LF;
        # check content independently of that checkout conversion.
        if not args.output.is_file() or args.output.read_bytes().replace(b"\r\n", b"\n") != generated:
            raise SystemExit("Physics catalogue is stale; run scripts/generate-physics-catalog.py")
        print("Deterministic catalogue matches: 34 bow / 21 arrow profiles, 588 bow / 25 ammo bindings")
    else:
        args.output.write_bytes(generated)
        print(f"Generated {args.output}")


if __name__ == "__main__":
    main()
