inline bool WeightGetterMatches(bool vr,bool readable,std::span<const std::uint8_t> bytes,float nativeDefault) noexcept {
    return vr && readable && nativeDefault==-1 && std::ranges::equal(bytes,NativeWeightGetter);
}
inline std::optional<std::array<std::uint8_t,NativeWeightGetter.size()>>
MakeWeightGetterClone(std::uintptr_t address,std::uintptr_t nativeDefault) noexcept {
    const auto maximum=static_cast<std::uintptr_t>(std::numeric_limits<std::intptr_t>::max());
    if (address>maximum-8 || nativeDefault>maximum) return std::nullopt;
    const auto distance=static_cast<std::intptr_t>(nativeDefault)-static_cast<std::intptr_t>(address+8);
    if (distance<std::numeric_limits<std::int32_t>::min() || distance>std::numeric_limits<std::int32_t>::max()) return std::nullopt;
    auto code=NativeWeightGetter;
    const auto data=static_cast<std::int32_t>(distance);
    std::memcpy(code.data()+4,&data,sizeof(data));
    // The LEA at +25 originally loads the game image base. Load an equivalent
    // pseudo-base (clone - original RVA) so both embedded dispatch tables and
    // their RVA entries resolve inside this independent snapshot. All local
    // branches stay intact; no instruction or table uses the patched body.
    const auto tableBase=-static_cast<std::int32_t>(WeightGetterRVA+32);
    std::memcpy(code.data()+28,&tableBase,sizeof(tableBase));
    return code;
}
