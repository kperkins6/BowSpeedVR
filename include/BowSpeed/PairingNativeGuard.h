namespace BowSpeed {
inline constexpr std::uintptr_t DrawGetterRVA=0x75CB00;
inline constexpr std::array<std::uint8_t,18> DrawGetterBytes={0x48,0x83,0xEC,0x28,0xE8,0x97,0xC4,0x01,0x00,0x48,0x83,0xC4,0x28,0xE9,0xFE,0x1D,0xC7,0xFF};
inline constexpr std::uintptr_t DrawPowerRVA=0x778FA0;
inline constexpr std::array<std::uint8_t,28> DrawPowerBytes={0x48,0x83,0xB9,0x58,0x01,0x00,0x00,0x00,0x74,0x09,0xF3,0x0F,0x10,0x05,0x76,0x16,0xE2,0x00,0xC3,0xF3,0x0F,0x10,0x81,0x88,0x01,0x00,0x00,0xC3};
inline constexpr std::uintptr_t DrawScaleRVA=0x3CE910;
inline constexpr std::array<std::uint8_t,52> DrawScaleBytes={0xF3,0x0F,0x5C,0x05,0x58,0xF6,0xAC,0x01,0xF3,0x0F,0x10,0x1D,0x08,0xBD,0x1C,0x01,0x0F,0x28,0xCB,0xF3,0x0F,0x5C,0x0D,0x45,0xF6,0xAC,0x01,0xF3,0x0F,0x5C,0x1D,0x55,0xF6,0xAC,0x01,0xF3,0x0F,0x5E,0xC1,0xF3,0x0F,0x59,0xC3,0xF3,0x0F,0x58,0x05,0x45,0xF6,0xAC,0x01,0xC3};
inline bool RecognizedPairingDraw(std::uintptr_t target,std::span<const std::uint8_t> getter,
    std::span<const std::uint8_t> power,std::span<const std::uint8_t> scale) {
    return target==DrawGetterRVA && std::ranges::equal(getter,DrawGetterBytes) &&
        std::ranges::equal(power,DrawPowerBytes) && std::ranges::equal(scale,DrawScaleBytes);
}
}
